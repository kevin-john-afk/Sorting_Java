package encupsulation;

public class boxproduct {
	 private String brand;
	    private int quantity;
	  
	    public boxproduct(String brand, int quantity) {
	        this.brand = brand;
	        this.quantity = quantity;
	    }
	
	    public String getBrand() {
	        return brand;
	    }
	 
	    public int getQuantity() {
	        return quantity;
	    }
	}


